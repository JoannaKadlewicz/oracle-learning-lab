def _structure_check(*tables):
    """Check query for ddl labs: columns, nullability and named-independent constraints."""
    names = ", ".join(f"'{t}'" for t in tables)
    return (
        "SELECT c.table_name, 'COLUMN' AS item,\n"
        "       c.column_name || ' ' || c.data_type\n"
        "       || CASE WHEN c.data_type = 'NUMBER' AND c.data_precision IS NOT NULL\n"
        "               THEN '(' || c.data_precision || ',' || c.data_scale || ')'\n"
        "               WHEN c.data_type IN ('VARCHAR2', 'CHAR') THEN '(' || c.char_length || ')' END\n"
        "       || DECODE(c.nullable, 'N', ' NOT NULL') AS detail\n"
        "FROM   user_tab_columns c\n"
        f"WHERE  c.table_name IN ({names})\n"
        "UNION ALL\n"
        "SELECT k.table_name, 'CONSTRAINT',\n"
        "       k.constraint_type || ' ' || LISTAGG(cc.column_name, ',') WITHIN GROUP (ORDER BY cc.position, cc.column_name)\n"
        "       || ' ' || MAX(r.table_name) || ' ' || MAX(DECODE(k.delete_rule, 'NO ACTION', NULL, k.delete_rule))\n"
        "FROM   user_constraints k\n"
        "JOIN   user_cons_columns cc ON cc.constraint_name = k.constraint_name\n"
        "LEFT JOIN user_constraints r ON r.constraint_name = k.r_constraint_name\n"
        f"WHERE  k.table_name IN ({names})\n"
        "AND    (k.constraint_type IN ('P', 'U', 'R')\n"
        "        OR (k.constraint_type = 'C' AND k.search_condition_vc NOT LIKE '\"%\" IS NOT NULL'))\n"
        "GROUP  BY k.table_name, k.constraint_name, k.constraint_type\n"
        "ORDER  BY 1, 2, 3"
    )


